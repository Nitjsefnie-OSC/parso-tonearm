#!/usr/bin/env python3
"""Translates the immutable starter-blends-aac-v1 release JSON into the checked-in Swift runtime
catalog (Sources/Domain/Mix/StarterBlendRuntimeData.swift). No planner, model or audio is run:
values are copied verbatim (Python repr round-trips doubles). Usage:
  generate-runtime-data.py starter-blend-source.json starter-transition-candidates.json out.swift"""
import json, sys

source = json.load(open(sys.argv[1]))
plans = json.load(open(sys.argv[2]))

def num(v):
    return repr(float(v))

facts = {}
for t in plans["transitions"]:
    for side in ("outgoingAnalysis", "incomingAnalysis"):
        a = t[side]
        facts[a["track_id"]] = a

order = [tid for b in source["blends"] for tid in b["tracks"]]
assert len(order) == 36 and len(set(order)) == 36, "expected 36 unique tracks"
assert len(plans["transitions"]) == 30

out = []
out.append("// Generated by tools/starter-blends/generate-runtime-data.py from the immutable release")
out.append("// starter-blends-aac-v1 (starter-blend-source.json + starter-transition-candidates.json).")
out.append("// Do not edit by hand and do not regenerate with a planner: the plans are authoritative.")
out.append("import Foundation\n")
out.append("enum StarterBlendRuntimeData {")
out.append("    static let edges: [StarterEdgePlan] = [")
for t in plans["transitions"]:
    p = t["plan"]
    style = {"bass-swap": ".bassSwap", "double-drop": ".doubleDrop", "phrase-cut": ".phraseCut"}[p["style"]]
    args = [f'blendID: "{t["blendID"]}"', f'edge: {t["edge"]}', f'outgoingTrackID: "{t["outgoing"]}"',
            f'incomingTrackID: "{t["incoming"]}"', f"style: {style}", f'tempo: {num(p["tempo"])}',
            f'overlapBeats: {p["overlapBeats"]}']
    for key, kind in (("incomingGain", "d"), ("outgoingSwapBeat", "i"), ("incomingSwapBeat", "i"),
                      ("blendStartSeconds", "d"), ("swapSeconds", "d"), ("blendEndSeconds", "d"),
                      ("incomingOffsetSeconds", "d")):
        if key in p:
            args.append(f"{key}: {num(p[key]) if kind == 'd' else p[key]}")
    if p["style"] == "phrase-cut":  # beats -> source seconds, once, so the plan is self-contained
        o, i = facts[t["outgoing"]], facts[t["incoming"]]
        args.append(f'outgoingStartSeconds: {num(o["phase"] + p["outgoingCutBeat"] * o["period"])}')
        args.append(f'incomingStartSeconds: {num(i["phase"] + p["incomingStartBeat"] * i["period"])}')
    out.append("        StarterEdgePlan(" + ", ".join(args) + "),")
out.append("    ]")
out.append("}")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
